"use client";

import Link from "next/link";
import { useState } from "react";
import { motion } from "motion/react";
import { Loader2, RefreshCw, ScanSearch } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Segmented } from "@/components/ui/segmented";
import type { AiDetectionReport, AiLabel } from "@/lib/api";
import { cn } from "@/lib/utils";
import {
  AiRing, AiSplitBar, DetectorSetupDialog, InstallProgress, useAiDetection, useDetector, verdictCopy,
  VerdictStamp,
} from "./ai-detection";
import { BACK, ringName, Shared } from "@/components/motion/transitions";

const LABEL_TEXT: Record<AiLabel, string> = {
  ai: "AI-generated",
  likely_ai: "Probably AI",
  possible: "Possibly AI",
  likely_human: "Probably human",
  human: "Human-written",
};

export function AiDetectionSection({ docId, initial, pIndex, arrived = false }: {
  docId: string;
  initial: AiDetectionReport | null;
  pIndex: Map<string, number>;
  /** The ring just morphed in from the review screen: show its value without replaying the count-up. */
  arrived?: boolean;
}) {
  const { report, running, run, status } = useAiDetection(docId, initial);
  const progress = useDetector((s) => s.progress);
  const [setup, setSetup] = useState(false);
  const [filter, setFilter] = useState<"all" | "ai">("all");

  const header = (
    <div className="mb-5">
      <h1 className="font-display text-[34px] leading-tight tracking-tight">AI detection</h1>
      <p className="mt-1 max-w-2xl text-sm text-muted-foreground">
        Estimates how much of this document reads like it was generated by an AI model such as ChatGPT, Claude, Gemini or Llama.
        Runs entirely on your computer.
      </p>
    </div>
  );

  if (!report?.available) {
    return (
      <>
        {header}
        <div className="hw-card p-8 text-center">
          <ScanSearch className="mx-auto size-8 text-muted-foreground" />
          {status?.ready ? (
            <>
              <p className="mt-3 font-medium">This document hasn&apos;t been checked yet</p>
              <p className="mt-1 text-sm text-muted-foreground">{report?.reason ?? "It was scanned before AI detection was turned on."}</p>
              <Button className="mt-4" onClick={run} disabled={running}>
                {running ? <><Loader2 className="animate-spin" /> Checking…</> : "Check for AI writing"}
              </Button>
            </>
          ) : progress ? (
            <InstallProgress className="mx-auto mt-4 max-w-sm" />
          ) : (
            <>
              <p className="mt-3 font-medium">AI detection isn&apos;t set up yet</p>
              <p className="mx-auto mt-1 max-w-md text-sm text-muted-foreground">
                It needs a one-time download of an open detection model (about 500 MB). After that it works offline, and
                your documents never leave this computer.
              </p>
              <Button className="mt-4" onClick={() => setSetup(true)}>Set up AI detection</Button>
            </>
          )}
        </div>
        <DetectorSetupDialog open={setup} onOpenChange={setSetup} onReady={run} />
      </>
    );
  }

  const r = report;
  const v = verdictCopy(r);
  const segments = (r.segments ?? []).filter((s) => filter === "all" || s.probability >= 0.5);
  const paraNo = (ids: string[]) => {
    const nums = ids.map((id) => pIndex.get(id)).filter((n): n is number => n !== undefined);
    if (!nums.length) return "";
    const lo = Math.min(...nums), hi = Math.max(...nums);
    return lo === hi ? `¶ ${lo}` : `¶ ${lo}–${hi}`;
  };
  const aiCount = (r.segments ?? []).filter((s) => s.probability >= 0.5).length;

  return (
    <>
      {header}
      <div className="relative mb-6 hw-card p-5 sm:p-6">
        <VerdictStamp report={r} className="pointer-events-none absolute -top-3 right-6 text-[13px]" delay={0.7} />
        <div className="flex flex-col items-start gap-6 sm:flex-row sm:flex-wrap sm:items-center sm:gap-8">
          <Shared name={ringName(docId)}><div><AiRing percent={r.ai_percent ?? null} size={148} stroke={11} instant={arrived} /></div></Shared>
          <div className="min-w-0 flex-1 sm:min-w-[260px]">
            <p className="font-display text-[30px] leading-tight">{v.title}</p>
            <p className="mt-1 text-sm text-muted-foreground">
              {r.ai_percent != null ? <>We estimate <b className="text-foreground">{r.ai_percent}%</b> of the checked text is AI-generated. {v.sub}</> : v.sub}
            </p>
            {r.ai_percent != null && <AiSplitBar report={r} className="mt-4 max-w-md" />}
            <p className="mt-3 text-xs text-muted-foreground">
              {r.words_scored?.toLocaleString()} of {r.words_total?.toLocaleString()} words checked · {r.segments?.length ?? 0} passages
              {" · "}{r.text_version === "current" ? "includes your accepted changes" : "original text"}
            </p>
          </div>
          <div className="flex flex-wrap gap-2 sm:flex-col">
            <Button variant="outline" size="sm" onClick={run} disabled={running}>
              {running ? <Loader2 className="animate-spin" /> : <RefreshCw />} Check again
            </Button>
            <Button variant="ghost" size="sm" render={<Link href={`/documents/${docId}?ai=1`} transitionTypes={BACK} />}>Highlight in document</Button>
          </div>
        </div>
      </div>

      <div className="mb-3 flex flex-wrap items-center justify-between gap-2">
        <h2 className="text-sm font-semibold">Passage by passage</h2>
        <Segmented value={filter} onChange={(x) => setFilter(x as "all" | "ai")} 
          options={[{ value: "all", label: "All passages" }, { value: "ai", label: `AI only (${aiCount})` }]} />
      </div>
      <div className="space-y-2">
        {segments.length === 0 && <p className="hw-card p-5 text-sm text-muted-foreground">No passages read as AI-generated.</p>}
        {segments.map((s, i) => {
          const pct = Math.round(s.probability * 100);
          const isAi = s.probability >= 0.5;
          const maybe = !isAi && s.label === "possible";
          return (
            <motion.div key={s.paragraph_ids.join("|") + i} initial={{ opacity: 0, y: 4 }} animate={{ opacity: 1, y: 0 }}
              transition={{ delay: Math.min(i, 12) * 0.03 }}
              className={cn("grid grid-cols-[64px_1fr] gap-3 hw-card p-4 sm:grid-cols-[88px_1fr] sm:gap-4", isAi && "border-brand/30")}>
              <div>
                <p className={cn("font-display text-2xl leading-none tabular-nums", isAi ? "text-brand" : maybe ? "text-warn" : "text-muted-foreground")}>{pct}%</p>
                <p className="mt-1 text-[11px] text-muted-foreground">AI likelihood</p>
                <div className="mt-2 h-1 overflow-hidden rounded-full bg-secondary">
                  <div className={cn("h-full", isAi ? "bg-brand" : maybe ? "bg-warn" : "bg-muted-foreground/40")} style={{ width: `${pct}%` }} />
                </div>
              </div>
              <div className="min-w-0">
                <div className="flex flex-wrap items-center gap-2 text-xs">
                  <span className={cn("rounded-full px-2 py-0.5", isAi ? "bg-brand-soft text-brand" : maybe ? "bg-warn-bg text-[oklch(0.45_0.1_70)]" : "bg-secondary text-muted-foreground")}>{LABEL_TEXT[s.label]}</span>
                  <span className="text-muted-foreground">{paraNo(s.paragraph_ids)} · {s.words} words</span>
                  <Link href={`/documents/${docId}?p=${s.paragraph_ids[0]}`} transitionTypes={BACK} className="ml-auto text-muted-foreground hover:text-foreground">Open</Link>
                </div>
                <p className="mt-2 line-clamp-2 font-serif text-[15px] leading-relaxed">
                  <span className={cn(isAi && "box-decoration-clone bg-[linear-gradient(transparent_58%,var(--color-highlighter)_58%)]")}>
                    {s.preview}{s.preview.length >= 160 ? "…" : ""}
                  </span>
                </p>
              </div>
            </motion.div>
          );
        })}
      </div>

      <details className="mt-6 hw-card p-4 text-sm">
        <summary className="cursor-pointer font-medium">How this works and how far to trust it</summary>
        <div className="mt-3 space-y-2 text-muted-foreground">
          <p>
            HumanWrite splits the document into passages of about 150–300 words and runs an open AI-text classifier on each one
            (Fakespot&apos;s RoBERTa detector, trained on human and AI writing from many models). The raw scores are calibrated so a
            passage marked 50% or higher is more likely AI than not. The headline figure is the share of checked words in those
            passages. In HumanWrite&apos;s tests it caught about 99% of AI passages and wrongly flagged about 4% of human ones.
          </p>
          <p>
            Like every AI detector, it can be wrong. Very formal or formulaic writing, text by non-native English speakers, and
            heavily edited AI text are the hardest cases. Headings, tables, references and passages under about 60 words aren&apos;t
            scored. Treat the result as an indicator, not proof of who wrote something.
          </p>
        </div>
      </details>
    </>
  );
}
